"""Compare port helpers to a pinned, unmodified official Humble dependency.

This checks the wire payload and NumPy semantics, not live ROS serialization.
Message containers are test doubles; the source dependency version installed
on the original robot is unknown and must be checked on that deployment.
"""
import array
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import struct
import sys
import types
import unittest
from unittest.mock import patch

try:
    import numpy as np
except ImportError:
    np = None

PACKAGE = Path(__file__).resolve().parents[1]


class Header:
    def __init__(self, **kwargs):
        self.__dict__.update(kwargs)


class PointField:
    INT8, UINT8, INT16, UINT16, INT32, UINT32, FLOAT32, FLOAT64 = range(1, 9)

    def __init__(self, name='', offset=0, datatype=0, count=0):
        self.name, self.offset, self.datatype, self.count = name, offset, datatype, count


class PointCloud2:
    def __init__(self, **kwargs):
        self.data = b''
        self.__dict__.update(kwargs)


def load(path, name):
    specification = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(specification)
    specification.loader.exec_module(module)
    return module


@unittest.skipIf(np is None, 'NumPy is required for point-cloud differential checks')
class PointCloudTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        sensor = types.ModuleType('sensor_msgs.msg')
        sensor.PointField, sensor.PointCloud2 = PointField, PointCloud2
        standard = types.ModuleType('std_msgs.msg')
        standard.Header = Header
        cls.modules = patch.dict(sys.modules, {'sensor_msgs.msg': sensor, 'std_msgs.msg': standard})
        cls.modules.start()
        cls.upstream = load(PACKAGE / 'test/fixtures/point_cloud2_humble.py', '_upstream_pc2')
        cls.port = load(PACKAGE / 'ctrl_ros1/ctrl_point_cloud2.py', '_port_pc2')

    @classmethod
    def tearDownClass(cls):
        cls.modules.stop()

    def fields(self):
        return [PointField(name=name, offset=4 * index, datatype=PointField.FLOAT32, count=1)
                for index, name in enumerate(('x', 'y', 'z', 'intensity'))]

    def assert_array_equal(self, actual, expected):
        self.assertEqual(actual.dtype, expected.dtype)
        self.assertEqual(actual.shape, expected.shape)
        np.testing.assert_array_equal(actual, expected)

    def compare_read(self, cloud, **kwargs):
        actual, expected = copy.deepcopy(cloud), copy.deepcopy(cloud)
        # ROS2 uint8[] message data is mutable even after DDS deserialization.
        expected.data = array.array('B', expected.data)
        left = self.port.read_points_numpy(actual, **kwargs)
        right = self.upstream.read_points_numpy(expected, **kwargs)
        self.assert_array_equal(left, right)
        self.assertEqual(bytes(actual.data), bytes(expected.data))
        return left

    def test_fixture_sha_and_git_blob_integrity(self):
        fixture = PACKAGE / 'test/fixtures/point_cloud2_humble.py'
        provenance = json.loads((fixture.parent / 'point_cloud2_provenance.json').read_text())
        payload = fixture.read_bytes()
        self.assertEqual(len(payload), provenance['bytes'])
        self.assertEqual(hashlib.sha256(payload).hexdigest(), provenance['sha256'])
        header = b'blob ' + str(len(payload)).encode() + b'\0'
        self.assertEqual(hashlib.sha1(header + payload).hexdigest(), provenance['blob_sha1'])

    def test_create_wire_payload_fields_dtype_and_ros1_uint8_serializer(self):
        fields = self.fields()
        points = np.array([[1, 2, 3, 4], [5, 6, 7, 8]], dtype=np.float32)
        left = self.port.create_cloud(Header(frame_id='lidar'), fields, points)
        right = self.upstream.create_cloud(Header(frame_id='lidar'), fields, points)
        for name in ('width', 'height', 'point_step', 'row_step', 'is_dense', 'is_bigendian'):
            self.assertEqual(getattr(left, name), getattr(right, name))
        self.assertEqual(bytes(left.data), bytes(right.data))
        # This is the same length+string operation generated by Noetic genpy
        # for non-list uint8[] fields. array.array is not accepted by 's'.
        wire = struct.pack('<I%ss' % len(left.data), len(left.data), left.data)
        self.assertEqual(wire[4:], bytes(right.data))
        with self.assertRaises(struct.error):
            struct.pack('<I%ss' % len(right.data), len(right.data), right.data)
        self.compare_read(left, field_names=('intensity', 'x'))

    def test_field_order_dtype_and_padding_are_unchanged(self):
        fields = [PointField('z', 8, PointField.FLOAT32, 1),
                  PointField('x', 0, PointField.FLOAT32, 1),
                  PointField('y', 4, PointField.FLOAT32, 1)]
        dtype = self.upstream.dtype_from_fields(fields, point_step=20)
        points = np.zeros(2, dtype=dtype)
        points['x'], points['y'], points['z'] = [1, 4], [2, 5], [3, 6]
        cloud = PointCloud2(data=points.tobytes(), width=2, height=1, point_step=20,
                            row_step=40, fields=fields, is_dense=False, is_bigendian=False)
        result = self.compare_read(cloud)
        self.assert_array_equal(result, np.array([[3, 1, 2], [6, 4, 5]], dtype=np.float32))

    def test_nan_selection_dense_flag_and_empty_cloud(self):
        points = np.array([[1, 2, 3, 4], [np.nan, 5, 6, 7], [8, 9, 10, np.nan]], dtype=np.float32)
        cloud = self.port.create_cloud(Header(), self.fields(), points)
        result = self.compare_read(cloud, field_names=('x', 'y', 'z'), skip_nans=True)
        self.assertEqual(len(result), 2)
        self.compare_read(cloud, skip_nans=False)
        cloud.is_dense = True
        result = self.compare_read(cloud, skip_nans=True)
        self.assertEqual(len(result), 3)
        empty = self.port.create_cloud(Header(), self.fields(), np.zeros((0, 4), dtype=np.float32))
        self.assertEqual(self.compare_read(empty).shape, (0, 4))

    def test_big_endian_immutable_ros1_buffer_and_repeated_read_semantics(self):
        points = np.array([[1, 2, 3, 4], [5, 6, 7, 8]], dtype='>f4')
        cloud = PointCloud2(data=points.tobytes(), width=2, height=1, point_step=16,
                            row_step=32, fields=self.fields(), is_dense=False, is_bigendian=True)
        result = self.compare_read(cloud)
        self.assert_array_equal(result, points.astype(np.float32))
        left, right = copy.deepcopy(cloud), copy.deepcopy(cloud)
        right.data = array.array('B', right.data)
        for _ in range(2):
            self.assert_array_equal(self.port.read_points_numpy(left), self.upstream.read_points_numpy(right))
            self.assertEqual(bytes(left.data), bytes(right.data))

    def test_organized_shape_flat_uvs_and_original_row_padding_behavior(self):
        points = np.arange(24, dtype=np.float32).reshape(3, 2, 4)
        cloud = self.port.create_cloud(Header(), self.fields(), points)
        self.assertEqual(self.compare_read(cloud, reshape_organized_cloud=True).shape, (3, 2, 4))
        self.compare_read(cloud, uvs=[0, 3, 5])
        # Humble reads contiguous width*height records, ignoring row_step.
        # Preserve that upstream limitation; do not silently repair row strides.
        cloud.row_step += 16
        cloud.data += bytes(32)
        self.compare_read(cloud)

    def test_scalar_types_counts_validation_assertions_and_mixed_field_error(self):
        for datatype in range(1, 9):
            with self.subTest(datatype=datatype):
                field = PointField('value', 0, datatype, 1)
                left = self.port.create_cloud(Header(), [field], [(1,), (2,)])
                right = self.upstream.create_cloud(Header(), [field], [(1,), (2,)])
                self.assertEqual(bytes(left.data), bytes(right.data))
                self.compare_read(left)
        field = PointField('vector', 0, PointField.FLOAT32, 3)
        self.assertEqual(self.port.dtype_from_fields([field]), self.upstream.dtype_from_fields([field]))
        cloud = self.port.create_cloud(Header(), self.fields(), [(1, 2, 3, 4)])
        for implementation in (self.port, self.upstream):
            with self.assertRaises(AssertionError):
                implementation.read_points_numpy(cloud, field_names=['missing'])
            with self.assertRaises(AssertionError):
                implementation.dtype_from_fields([PointField('zero', 0, PointField.FLOAT32, 0)])
            with self.assertRaises(AssertionError):
                implementation.dtype_from_fields([self.fields()[0], self.fields()[0]])
        cloud.fields[-1].datatype = PointField.UINT32
        for implementation in (self.port, self.upstream):
            with self.assertRaises(AssertionError):
                implementation.read_points_numpy(cloud, field_names=('x', 'y', 'z'))


if __name__ == '__main__':
    unittest.main()
